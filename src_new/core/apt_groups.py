from functools import lru_cache


@lru_cache(maxsize=1)
def _alias_index() -> dict:
    idx = {}
    for _, name, aliases in GROUPS:
        idx[name.lower()] = name
        for a in aliases:
            idx[a.lower()] = name
    return idx


def canonical_name(raw: str):
    """别名 → ATT&CK 正名（大小写不敏感）；未收录返回 None。"""
    return _alias_index().get((raw or "").strip().lower())


@lru_cache(maxsize=1)
def candidate_groups_text() -> str:
    """候选名单文本（正名 + 别名），注入归因 prompt 用。"""
    parts = []
    for _, name, aliases in GROUPS:
        parts.append(f"{name} ({'; '.join(aliases)})" if aliases else name)
    return "; ".join(parts)
